#!/usr/bin/env python3
"""Group the reports merged into ticket #4471 by cause. Read-only over src/lib/data/.

Run: python3 scripts/analyze.py > scripts/analysis.md

The cause rule is the kb's own rule (src/lib/kb/causes.ts), ported:
- the tenant locale writes the day first (all 11 tenants do; checked with Node Intl),
- channel 'form' on a booking-v3 tenant (hint MM/DD/YYYY) -> 'hint', else -> 'parser'.
On top of that, the script reads every body and checks the two dates in it:
a day/month flip ("5 March" -> "3 May") fits both causes; a one-day move does not.
"""
import collections
import datetime
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "lib", "data")
MONTHS = "January February March April May June July August September October November December".split()
WEEKDAYS = "Monday Tuesday Wednesday Thursday Friday Saturday Sunday".split()
DATE = re.compile(r"(?:(" + "|".join(WEEKDAYS) + r") )?(\d{1,2}) (" + "|".join(MONTHS) + r")")
DAY_FIRST = {"en-GB", "en-IE", "de-DE", "es-ES", "nl-NL", "cs-CZ", "it-IT", "fr-FR", "pl-PL", "pt-PT", "da-DK"}
YEAR = 2026

raw = json.load(open(os.path.join(ROOT, "reports-4471.json")))
tenants = {t["handle"]: t for t in (json.load(open(f)) for f in glob.glob(os.path.join(ROOT, "tenants", "*.json")))}
notes = json.load(open(os.path.join(ROOT, "desk-notes.json")))

# 1. Duplicates: same id more than once. Check they are identical copies.
by_id = collections.defaultdict(list)
for r in raw:
    by_id[r["id"]].append(r)
dups = {i: rs for i, rs in by_id.items() if len(rs) > 1}
dup_identical = all(len({json.dumps(x, sort_keys=True) for x in rs}) == 1 for rs in dups.values())
reports = [rs[0] for rs in by_id.values()]


def cause_of(r):
    t = tenants.get(r["tenant"])
    if not t or t["locale"] not in DAY_FIRST:
        return None
    return "hint" if r["channel"] == "form" and t["form"] == "booking-v3" else "parser"


def shape_of(body):
    """flip | one-day | weekday-only | no-dates."""
    ds = DATE.findall(body)
    if len(ds) == 2:
        (_, d1, m1), (_, d2, m2) = ds
        a, b = (int(d1), MONTHS.index(m1) + 1), (int(d2), MONTHS.index(m2) + 1)
        if a == (b[1], b[0]):
            return "flip"
        da, db = datetime.date(YEAR, a[1], a[0]), datetime.date(YEAR, b[1], b[0])
        if abs((da - db).days) == 1:
            return "one-day"
        return "other-pair"
    if re.search(r"one day off|before I made the booking|Tuesday\. .*Monday|showed as Monday", body):
        return "one-day"
    return "no-dates"


def weekday_errors(body):
    bad = []
    for w, d, m in DATE.findall(body):
        if w and datetime.date(YEAR, MONTHS.index(m) + 1, int(d)).strftime("%A") != w:
            bad.append(f"{w} {d} {m}")
    return bad


rows = []
for r in reports:
    rows.append({**r, "cause": cause_of(r), "shape": shape_of(r["body"]), "tag": r["meta"]["intakeTag"],
                 "form": tenants[r["tenant"]]["form"], "badwd": weekday_errors(r["body"])})


def problem_of(x):
    if x["shape"] == "one-day":
        return "one-day-move"
    if x["shape"] == "no-dates":
        return f"{x['cause']}-vague"
    return x["cause"]


groups = collections.defaultdict(list)
for x in rows:
    groups[problem_of(x)].append(x)

out = []
p = out.append
p("# S01E03 analysis of ticket #4471 (generated by analyze.py)\n")
p(f"- rows in reports-4471.json: **{len(raw)}**")
p(f"- unique ids: **{len(reports)}** ({len(raw) - len(reports)} extra rows from {len(dups)} ids exported twice; identical copies: {dup_identical})")
p(f"- duplicated ids: {', '.join(sorted(dups))}")
p(f"- mergedInto values: {dict(collections.Counter(r['mergedInto'] for r in reports))}")
p(f"- tenants in reports not in the tenant directory: {sorted({r['tenant'] for r in reports} - set(tenants)) or 'none'}")
p(f"- received {min(r['receivedAt'] for r in reports)} .. {max(r['receivedAt'] for r in reports)}")
p("")
p("## Kb rule (causes.ts) over the 412 unique reports\n")
kb = collections.Counter(x["cause"] for x in rows)
p("| cause | reports |\n|---|---|")
for c, n in kb.most_common():
    p(f"| {c} | {n} |")
p(f"| **total** | **{sum(kb.values())}** |\n")
p(f"Kb rule on the 427 raw rows (no dedupe): {dict(collections.Counter(cause_of(r) for r in raw))}\n")

p("## Body shape (two dates in the body)\n")
p("| shape | reports |\n|---|---|")
for s, n in collections.Counter(x["shape"] for x in rows).most_common():
    p(f"| {s} | {n} |")
p("")

p("## Problems (cause + body shape)\n")
p("| problem | reports | ids |\n|---|---|---|")
for g, xs in sorted(groups.items(), key=lambda kv: -len(kv[1])):
    p(f"| {g} | {len(xs)} | {', '.join(x['id'] for x in xs)} |")
p(f"| **total** | **{sum(len(v) for v in groups.values())}** | |\n")

p("## Cross-checks\n")
for g, xs in sorted(groups.items(), key=lambda kv: -len(kv[1])):
    p(f"### {g} ({len(xs)})")
    p(f"- intake tag: {dict(collections.Counter(x['tag'] for x in xs))}")
    p(f"- channel: {dict(collections.Counter(x['channel'] for x in xs))}")
    p(f"- booking form: {dict(collections.Counter(x['form'] for x in xs))}")
    p(f"- tenants: {len({x['tenant'] for x in xs})} · seen {min(x['receivedAt'][:10] for x in xs)} -> {max(x['receivedAt'][:10] for x in xs)}")
    for x in xs[:2] if len(xs) > 10 else xs:
        p(f"- {x['id']} {x['tenant']} {x['channel']}: \"{x['body']}\"")
    p("")

hint_ids = {x["id"] for x in rows if x["cause"] == "hint"}
tag_hint = {x["id"] for x in rows if x["tag"] == "hint"}
p("### intake tag vs kb cause")
p(f"- tagged hint: {len(tag_hint)} · kb cause hint: {len(hint_ids)} · both: {len(tag_hint & hint_ids)}")
p(f"- tagged hint but cause parser: {len(tag_hint - hint_ids)}: {', '.join(sorted(tag_hint - hint_ids))}")
p(f"- cause hint but tagged parser: {len(hint_ids - tag_hint)}: {', '.join(sorted(hint_ids - tag_hint))}\n")

one_day = sorted(x["id"] for x in groups["one-day-move"])
p("### desk-notes.json oneDayMove")
p(f"- desk list: {notes['oneDayMove']}")
p(f"- script one-day: {one_day}")
p(f"- same set: {set(one_day) == set(notes['oneDayMove'])}")
p(f"- kb cause of those: {dict(collections.Counter(x['cause'] for x in groups['one-day-move']))} (CauseTable counts them inside that cause, as a footnote)\n")

p("### weekday names that do not match the date in 2026")
bad = [(x["id"], x["badwd"]) for x in rows if x["badwd"]]
p(f"- {len(bad)} reports" + ("".join(f"\n  - {i}: {b}" for i, b in bad) if bad else ""))
p("")

print("\n".join(out))
